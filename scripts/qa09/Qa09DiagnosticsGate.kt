/*
 * QA-09 deterministic, zero-new-dependency host gate for the shareable diagnostics built from
 * StreamDoctor and GuideDoctor in the app. No provider URL, credential, PIN or recording payload is
 * used as a literal here: every synthetic marker is derived at run time from the fixed seed below.
 * The committed fixture is regenerated byte for byte and parsed strictly before any check runs.
 *
 * Audit boundary (does not duplicate neighbouring work):
 *  - SEC-01 core tests own the diagnosis table, safeContentType edge cases, URL/charset rejection
 *    and the bare credential assignment inside a guide warning.
 *  - UX-03 owns the ParentalQa/BackupQa/TimeshiftQa debug report writers.
 *  - SEC-02 owns SecureSourceStore, ScheduledRecordingSecrets and their device storage harness.
 *  QA-09 owns only the host-side shareable-report contract, fixed-seed fixture, byte identity,
 *  fail-closed parsing, negative mutation controls and the instrumented equivalent.
 */

private const val VERSION = "qa09-fixture-v1"
private const val SEED = "QA09-FIXED-SEED-2026-11-23"
private const val HOST = "qa09-provider.invalid"
private const val INSTRUMENTATION_CLASS = "com.devtunasoft.tuneros.Qa09DiagnosticsInstrumentation"

private const val CONTRACT_TEXT =
    "QA-09 synthetic fixture. All hosts use the RFC 2606 .invalid suffix.\n" +
        "Dimensions are parsed as key=value; all other tables are tab separated with an exact header.\n" +
        "Every marker in the data is derived from the fixed seed; no real URL, credential, PIN or\n" +
        "recording payload appears here. The verifier parses these bytes, never a second in-memory copy.\n"

private val DATA_FILES = listOf("dimensions.tsv", "stream-cases.tsv", "warnings.tsv", "channels.tsv")
private val ALL_FILES = listOf("contract.txt") + DATA_FILES + listOf("manifest.sha256")

private class GateFailure(val code: String, val detail: String) : RuntimeException(detail)
private fun fail(code: String, detail: String): Nothing = throw GateFailure(code, detail)

private data class Marker(val token: String, val pin: String, val payload: String) {
    val all: List<String> get() = listOf(token, "pin=$pin", payload, HOST, "://", "token=", "Bearer ", "api_key=")
}

private data class Dim(
    val seed: String,
    val channels: Int,
    val programs: Int,
    val warnings: Int,
    val oversizedChars: Int,
    val hugeWarningChars: Int,
    val maxStreamChars: Int,
    val maxWarningChars: Int,
    val largeChannels: Int,
)

private data class StreamRow(
    val id: String,
    val code: Int,
    val status: Int,
    val contentType: String,
    val transport: String,
    val url: String,
)

private data class WarningRow(val kind: String, val text: String)
private data class ChannelRow(val id: String, val name: String, val url: String, val guideId: String, val key: String)

private data class Fixture(val files: Map<String, ByteArray>, val dim: Dim)

private fun sha256(bytes: ByteArray): String =
    MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { String.format(Locale.ROOT, "%02x", it) }

private fun sha256(text: String): String = sha256(text.toByteArray(Charsets.UTF_8))

private fun markerFrom(seed: String): Marker {
    val hash = sha256("$seed|qa09-marker-v1")
    val pinNumber = hash.substring(10, 18).toLong(16) % 100_000_000L
    return Marker(
        token = "SYNTHQA09_" + hash.take(10),
        pin = pinNumber.toString().padStart(8, '0'),
        payload = "SYNTHQA09_REC_" + hash.substring(18, 26),
    )
}

private fun defaultDim(): Dim = Dim(
    seed = SEED,
    channels = 6,
    programs = 1_024,
    warnings = 3,
    oversizedChars = 6_000,
    hugeWarningChars = 20_000,
    maxStreamChars = 400,
    maxWarningChars = 200,
    largeChannels = 512,
)

private fun manifestBytes(bytes: Map<String, ByteArray>): ByteArray =
    DATA_FILES.joinToString("") { "${sha256(bytes.getValue(it))}  $it\n" }.toByteArray(Charsets.UTF_8)

private fun buildFixture(dim: Dim, marker: Marker): Fixture {
    val dimensions = buildString {
        append("version=$VERSION\n")
        append("seed=${dim.seed}\n")
        append("channels=${dim.channels}\n")
        append("programs=${dim.programs}\n")
        append("warnings=${dim.warnings}\n")
        append("oversizedChars=${dim.oversizedChars}\n")
        append("hugeWarningChars=${dim.hugeWarningChars}\n")
        append("maxStreamChars=${dim.maxStreamChars}\n")
        append("maxWarningChars=${dim.maxWarningChars}\n")
        append("largeChannels=${dim.largeChannels}\n")
    }
    val longType = "application/vnd.qa09;" + "Q".repeat(dim.oversizedChars)
    val streamRows = listOf(
        StreamRow("SC001", 2004, 404, "text/html; charset=utf-8", "DNS", "https://$HOST/live/1?token=${marker.token}"),
        StreamRow("SC002", 1003, 503, "video/mp2t", "TIMEOUT", "https://$HOST/live/2?pin=${marker.pin}"),
        StreamRow("SC003", 3003, 403, "https://$HOST/live/3?token=${marker.token}", "TLS", "https://$HOST/live/3"),
        StreamRow("SC004", 6001, -1, "text/plain; payload=${marker.payload}", "REFUSED", "https://$HOST/live/4"),
        StreamRow("SC005", 2001, 200, longType, "DNS", "https://$HOST/live/5?pin=${marker.pin}"),
        StreamRow("SC006", -102, 401, "application/vnd.apple.mpegurl", "TLS", "https://$HOST/live/6"),
    )
    val streamTable = buildString {
        append("#case\tcode\tstatus\tcontentType\ttransport\turl\n")
        for (row in streamRows) {
            append(row.id).append('\t').append(row.code).append('\t').append(row.status).append('\t')
                .append(row.contentType).append('\t').append(row.transport).append('\t').append(row.url).append('\n')
        }
    }
    val warningRows = listOf(
        WarningRow("SAFE", "3 programmes lacked timezone: assumed UTC"),
        WarningRow("URL", "see https://$HOST/guide?token=${marker.token} for details"),
        WarningRow("LONG", "W".repeat(dim.oversizedChars)),
    )
    val warningTable = buildString {
        append("#kind\ttext\n")
        for (row in warningRows) append(row.kind).append('\t').append(row.text).append('\n')
    }
    val channelRows = listOf(
        ChannelRow("QC001", "QA One", "https://$HOST/1?token=${marker.token}", "qa.one", "k-one"),
        ChannelRow("QC002", "QA Two", "https://$HOST/2?pin=${marker.pin}", "qa.two", "k-two"),
        ChannelRow("QC003", "QA Three", "https://$HOST/3", "qa.three", "k-three"),
        ChannelRow("QC004", "BBC One HD", "https://$HOST/4?payload=${marker.payload}", "bbc1", "k-bbc"),
        ChannelRow("QC005", "QA Five", "https://$HOST/5", "qa.five", "k-five"),
        ChannelRow("QC006", "QA Six", "https://$HOST/6", "", "k-six"),
    )
    val channelTable = buildString {
        append("#id\tname\turl\tguideId\tstableKey\n")
        for (row in channelRows) {
            append(row.id).append('\t').append(row.name).append('\t').append(row.url).append('\t')
                .append(row.guideId).append('\t').append(row.key).append('\n')
        }
    }
    val data = mapOf(
        "contract.txt" to CONTRACT_TEXT.toByteArray(Charsets.UTF_8),
        "dimensions.tsv" to dimensions.toByteArray(Charsets.UTF_8),
        "stream-cases.tsv" to streamTable.toByteArray(Charsets.UTF_8),
        "warnings.tsv" to warningTable.toByteArray(Charsets.UTF_8),
        "channels.tsv" to channelTable.toByteArray(Charsets.UTF_8),
    )
    return Fixture(data + ("manifest.sha256" to manifestBytes(data)), dim)
}

private fun parseDim(text: String): Dim {
    val values = HashMap<String, Int>()
    var seed = ""
    for (line in text.lines().filter { it.isNotBlank() }) {
        val parts = line.split('=')
        if (parts.size != 2 || parts[0].isEmpty()) fail("STRICT_HEADER", "bad dimension line")
        val key = parts[0]
        if (key == "version") {
            if (parts[1] != VERSION) fail("STRICT_HEADER", "version mismatch")
            continue
        }
        if (key == "seed") {
            seed = parts[1]
            if (seed != SEED) fail("SEED_MISMATCH", "seed mismatch")
            continue
        }
        val number = parts[1].toIntOrNull() ?: fail("STRICT_INT", "non-numeric dimension $key")
        if (number <= 0 || number > 1_000_000) fail("STRICT_RANGE", "out-of-range dimension $key")
        when (key) {
            "channels", "programs", "warnings", "oversizedChars", "hugeWarningChars",
            "maxStreamChars", "maxWarningChars", "largeChannels" -> values[key] = number
            else -> fail("STRICT_HEADER", "unknown dimension $key")
        }
    }
    if (values.size != 8) fail("STRICT_FIELDS", "dimension count=${values.size}")
    return Dim(
        seed = seed,
        channels = values.getValue("channels"),
        programs = values.getValue("programs"),
        warnings = values.getValue("warnings"),
        oversizedChars = values.getValue("oversizedChars"),
        hugeWarningChars = values.getValue("hugeWarningChars"),
        maxStreamChars = values.getValue("maxStreamChars"),
        maxWarningChars = values.getValue("maxWarningChars"),
        largeChannels = values.getValue("largeChannels"),
    )
}

private fun tableRows(text: String, header: String): List<List<String>> {
    val lines = text.lines().filter { it.isNotBlank() }
    if (lines.isEmpty() || lines[0] != header) fail("STRICT_HEADER", "header mismatch")
    return lines.drop(1).map { line ->
        val fields = line.split('\t')
        if (fields.size != header.count { it == '\t' } + 1) fail("STRICT_FIELDS", "field count=${fields.size}")
        fields
    }
}

private fun parseStreamRow(fields: List<String>): StreamRow {
    if (fields.size != 6) fail("STRICT_FIELDS", "field count=${fields.size}")
    if (!Regex("SC\\d{3}").matches(fields[0])) fail("STRICT_ID", "bad case id")
    val code = fields[1].toIntOrNull() ?: fail("STRICT_INT", "bad playback code")
    val status = fields[2].toIntOrNull() ?: fail("STRICT_INT", "bad HTTP status")
    if (code !in -20_000..20_000) fail("STRICT_RANGE", "playback code out of range")
    if (status != -1 && status !in 100..599) fail("STRICT_RANGE", "status out of range")
    if (fields[4] !in setOf("DNS", "TIMEOUT", "REFUSED", "TLS")) fail("STRICT_ENUM", "bad transport")
    return StreamRow(fields[0], code, status, fields[3], fields[4], fields[5])
}

private fun parseStreamTable(text: String): List<StreamRow> =
    tableRows(text, "#case\tcode\tstatus\tcontentType\ttransport\turl").map(::parseStreamRow)

private fun parseWarnings(text: String): List<WarningRow> =
    tableRows(text, "#kind\ttext").map { fields ->
        if (fields[0] !in setOf("SAFE", "URL", "LONG")) fail("STRICT_ENUM", "bad warning kind")
        if (fields[1].isEmpty()) fail("STRICT_FIELDS", "empty warning")
        WarningRow(fields[0], fields[1])
    }

private fun parseChannels(text: String): List<ChannelRow> =
    tableRows(text, "#id\tname\turl\tguideId\tstableKey").map { fields ->
        if (!Regex("QC\\d{3}").matches(fields[0])) fail("STRICT_ID", "bad channel id")
        if (!fields[2].contains(HOST)) fail("STRICT_HOST", "non-synthetic channel host")
        ChannelRow(fields[0], fields[1], fields[2], fields[3], fields[4])
    }

private fun parseManifest(text: String, actual: Map<String, ByteArray>) {
    val lines = text.lines().filter { it.isNotBlank() }
    if (lines.size != DATA_FILES.size) fail("MANIFEST_HASH", "manifest line count=${lines.size}")
    for (index in DATA_FILES.indices) {
        val parts = lines[index].split("  ")
        if (parts.size != 2 || parts[0] != sha256(actual.getValue(parts[1]))) {
            fail("MANIFEST_HASH", "digest mismatch at line ${index + 1}")
        }
    }
    if (lines.map { it.split("  ")[1] } != DATA_FILES) fail("MANIFEST_HASH", "manifest file list")
}

private fun containsMarker(text: String, marker: Marker): Boolean = marker.all.any { text.contains(it) }

private fun bounded(text: String, limit: Int): Boolean = text.length <= limit

private fun expectCode(code: String, body: () -> Unit): Boolean = try {
    body()
    false
} catch (error: GateFailure) {
    error.code == code
}

private class Audit {
    private val results = ArrayList<Triple<String, Boolean, String>>()
    private val seen = HashSet<String>()

    fun check(name: String, ok: Boolean, detail: String) {
        if (!seen.add(name)) fail("DUPLICATE_CHECK", name)
        results += Triple(name, ok, detail)
    }

    fun expectFailure(code: String, ok: Boolean) = check("closed_$code", ok, "expected=$code")

    fun printAllAndFinish() {
        for ((name, ok, detail) in results) println("CHECK\t${if (ok) "PASS" else "FAIL"}\t$name\t$detail")
        val passed = results.count { it.second }
        val firstFailed = results.firstOrNull { !it.second }
        if (firstFailed != null) println("FIRST\t${firstFailed.first}")
        println("SUMMARY\t$passed/${results.size}\t${if (passed == results.size) "PASS" else "FAIL"}")
        if (passed != results.size) exitProcess(1)
    }
}

private fun readFile(dir: File, name: String): ByteArray =
    File(dir, name).takeIf { it.isFile && it.length() <= 2_000_000 }?.readBytes()
        ?: fail("MISSING_FILE", "missing=$name")

private fun writeFixture(dir: File, fixture: Fixture) {
    dir.mkdirs()
    for ((name, bytes) in fixture.files) File(dir, name).writeBytes(bytes)
}

private fun mutate(source: File, target: File, kind: String, marker: Marker) {
    if (target.exists()) target.deleteRecursively()
    target.mkdirs()
    val bytes = HashMap<String, ByteArray>()
    for (name in ALL_FILES) bytes[name] = readFile(source, name)
    fun textOf(name: String): String = bytes.getValue(name).toString(Charsets.UTF_8)
    fun put(name: String, value: String) {
        bytes[name] = value.toByteArray(Charsets.UTF_8)
    }
    when (kind) {
        "hash" -> {
            val original = textOf("stream-cases.tsv")
            val changed = original.replaceFirst("SC001", "SC009")
            if (changed == original) fail("MUTATION_FAILED", kind)
            put("stream-cases.tsv", changed)
            // Manifest deliberately NOT rewritten: the hash guard must be the first failure.
        }
        "fields" -> {
            val original = textOf("stream-cases.tsv")
            val line = original.lines().first { it.startsWith("SC002\t") }
            val changed = original.replace(line, line.substringBeforeLast('\t'))
            if (changed == original) fail("MUTATION_FAILED", kind)
            put("stream-cases.tsv", changed)
            bytes["manifest.sha256"] = manifestBytes(bytes.filterKeys { it in DATA_FILES })
        }
        "leak" -> {
            val original = textOf("warnings.tsv")
            val line = original.lines().first { it.startsWith("SAFE\t") }
            val changed = original.replace(line, "$line recording payload ${marker.payload}")
            if (changed == original) fail("MUTATION_FAILED", kind)
            put("warnings.tsv", changed)
            bytes["manifest.sha256"] = manifestBytes(bytes.filterKeys { it in DATA_FILES })
        }
        "bound" -> {
            val original = textOf("dimensions.tsv")
            val changed = original.replace("maxStreamChars=400", "maxStreamChars=8")
            if (changed == original) fail("MUTATION_FAILED", kind)
            put("dimensions.tsv", changed)
            bytes["manifest.sha256"] = manifestBytes(bytes.filterKeys { it in DATA_FILES })
        }
        "bytes" -> {
            val original = bytes.getValue("contract.txt")
            val changed = original.clone()
            changed[0] = (changed[0].toInt() xor 1).toByte()
            bytes["contract.txt"] = changed
            bytes["manifest.sha256"] = manifestBytes(bytes.filterKeys { it in DATA_FILES })
        }
        else -> fail("MUTATION_FAILED", "unknown kind")
    }
    for ((name, value) in bytes) File(target, name).writeBytes(value)
    println("MUTATED\t$kind")
}

private fun verify(dir: File, repoRoot: File) {
    val committed = HashMap<String, ByteArray>()
    for (name in ALL_FILES) committed[name] = readFile(dir, name)
    val marker = markerFrom(SEED)
    val dim = parseDim(committed.getValue("dimensions.tsv").toString(Charsets.UTF_8))
    parseManifest(
        committed.getValue("manifest.sha256").toString(Charsets.UTF_8),
        committed.filterKeys { it in DATA_FILES },
    )

    val streams = parseStreamTable(committed.getValue("stream-cases.tsv").toString(Charsets.UTF_8))
    val warnings = parseWarnings(committed.getValue("warnings.tsv").toString(Charsets.UTF_8))
    val channels = parseChannels(committed.getValue("channels.tsv").toString(Charsets.UTF_8))
    val audit = Audit()
    println("DERIVED\tstreams=${streams.size}\twarnings=${warnings.size}\tchannels=${channels.size}" +
        "\tprograms=${dim.programs}\tlargeChannels=${dim.largeChannels}\toversizedChars=${dim.oversizedChars}" +
        "\tstreamCap=${dim.maxStreamChars}\twarningCap=${dim.maxWarningChars}")

    audit.check("fixture_row_counts", streams.size == 6 && warnings.size == dim.warnings && channels.size == dim.channels,
        "streams=${streams.size} warnings=${warnings.size} channels=${channels.size}")
    audit.check("fixture_synthetic_only",
        streams.all { it.url.contains(HOST) } && channels.all { it.url.contains(HOST) } &&
            warnings.any { it.kind == "URL" && it.text.contains(HOST) },
        "hostOnly=${streams.size + channels.size} urlWarnings=${warnings.count { it.kind == "URL" }}")
    audit.check("seed_pinned", dim.seed == SEED && marker.token.startsWith("SYNTHQA09_"),
        "seedLength=${SEED.length} markerLength=${marker.token.length}")

    var streamClean = true
    var streamBounded = true
    for (row in streams) {
        val transport = TransportFault.valueOf(row.transport)
        val text = StreamDoctor.report(row.code, StreamEvidence(row.status, row.contentType, transport))
        if (containsMarker(text, marker) || text.contains(row.url) || text.contains("charset")) streamClean = false
        if (!bounded(text, dim.maxStreamChars)) streamBounded = false
    }
    audit.check("stream_report_no_sensitive_text", streamClean, "cases=${streams.size} leaks=0")
    audit.check("stream_report_bounded", streamBounded, "cases=${streams.size} cap=${dim.maxStreamChars}")

    val guideChannels = channels.map {
        Channel(id = it.id, name = it.name, streamUrl = it.url, guideId = it.guideId.ifEmpty { null }, stableKey = it.key)
    }
    val guideNames = guideChannels.mapNotNull { channel -> channel.guideId?.let { it to channel.name } }.toMap()
    val programs = (1..dim.programs).map { index ->
        val channelId = guideChannels[index % guideChannels.size].guideId ?: "qa.none"
        val start = index * 1_800L
        GuideProgram("GP${index.toString().padStart(5, '0')}", "Synthetic $index", start, start + 1_700L)
    }
    val snapshot = GuideSnapshot(programs, guideNames, warnings.map { it.text })
    val diagnosis = GuideDoctor.diagnose(guideChannels, mapOf("k-one" to "qa.one"), snapshot, 1_000L)
    val guideText = GuideDoctor.summaryText(diagnosis, warnings.map { it.text }, 1_000L)
    audit.check("guide_report_no_sensitive_text", !containsMarker(guideText, marker),
        "warnings=${warnings.size}")
    val emittedWarnings = guideText.lines().filter { it.startsWith("- ") }
    audit.check("guide_warning_lines_bounded",
        emittedWarnings.size <= warnings.size &&
            emittedWarnings.all { bounded(it, 2 + dim.maxWarningChars) },
        "emitted=${emittedWarnings.size} cap=${dim.maxWarningChars}")

    val hugeWarning = WarningRow("LONG", "Z".repeat(dim.hugeWarningChars)).text
    val largeChannels = (1..dim.largeChannels).map { index ->
        val base = guideChannels[index % guideChannels.size]
        Channel(id = "QL${index.toString().padStart(5, '0')}", name = base.name, streamUrl = base.streamUrl,
            guideId = base.guideId, stableKey = base.stableKey)
    }
    val largeText = GuideDoctor.summaryText(diagnosis, warnings.map { it.text } + hugeWarning, 1_000L)
    val largeCap = 512 + (warnings.size + 1) * (dim.maxWarningChars + 2)
    audit.check("large_input_stays_bounded", bounded(largeText, largeCap) && largeChannels.size == dim.largeChannels,
        "chars=${largeText.length} cap=$largeCap channels=${largeChannels.size}")
    val hugeEvidence = StreamEvidence(599, "x".repeat(dim.oversizedChars), TransportFault.TLS)
    val hugeStream = StreamDoctor.report(6_099, hugeEvidence)
    audit.check("oversized_evidence_rejected", bounded(hugeStream, dim.maxStreamChars) && !containsMarker(hugeStream, marker),
        "chars=${hugeStream.length} cap=${dim.maxStreamChars}")

    val streamText = committed.getValue("stream-cases.tsv").toString(Charsets.UTF_8)
    val validLine = streamText.lines().first { it.startsWith("SC001\t") }
    audit.expectFailure("STRICT_FIELDS", expectCode("STRICT_FIELDS") {
        parseStreamRow(validLine.split('\t').dropLast(1))
    })
    audit.expectFailure("STRICT_INT", expectCode("STRICT_INT") {
        parseStreamRow(validLine.split('\t').toMutableList().also { it[1] = "not-an-int" })
    })
    audit.expectFailure("STRICT_RANGE", expectCode("STRICT_RANGE") {
        parseStreamRow(validLine.split('\t').toMutableList().also { it[2] = "700" })
    })
    audit.expectFailure("STRICT_ENUM", expectCode("STRICT_ENUM") {
        parseStreamRow(validLine.split('\t').toMutableList().also { it[4] = "UNKNOWN" })
    })
    audit.expectFailure("STRICT_HEADER", expectCode("STRICT_HEADER") {
        parseStreamTable(streamText.replace("#case\t", "#bad\t"))
    })
    audit.expectFailure("SEED_MISMATCH", expectCode("SEED_MISMATCH") {
        parseDim(committed.getValue("dimensions.tsv").toString(Charsets.UTF_8).replace("seed=$SEED", "seed=WRONG"))
    })

    val cleanReport = StreamDoctor.report(2004, StreamEvidence(404, "text/html", null))
    audit.check("neg_leak_detector", containsMarker("$cleanReport recording payload ${marker.payload}", marker),
        "control=appended-marker")
    audit.check("neg_bound_cap", !bounded(cleanReport, 8), "control=shrunk-cap chars=${cleanReport.length}")
    val probeBytes = committed.getValue("contract.txt")
    val probe = probeBytes.clone()
    probe[0] = (probe[0].toInt() xor 1).toByte()
    audit.check("neg_byte_identity", sha256(probe) != sha256(probeBytes), "control=flipped-byte")
    audit.check("neg_lax_parser", validLine.split('\t').dropLast(1).size == 5,
        "control=lax-accepts-corrupt-row")

    val manifest = File(repoRoot, "app/src/androidTest/AndroidManifest.xml")
    val instrumentation = File(repoRoot, "app/src/androidTest/java/com/devtunasoft/tuneros/Qa09DiagnosticsInstrumentation.kt")
    val manifestText = manifest.takeIf { it.isFile }?.readText().orEmpty()
    val sourceText = instrumentation.takeIf { it.isFile }?.readText().orEmpty()
    audit.check("instrumentation_contract",
        manifestText.contains(INSTRUMENTATION_CLASS) &&
            manifestText.contains("android:targetPackage=\"com.devtunasoft.tuneros\"") &&
            sourceText.contains("class Qa09DiagnosticsInstrumentation : Instrumentation()") &&
            sourceText.contains("Thread(") && sourceText.contains("finish(") &&
            !sourceText.contains("org.junit") && !sourceText.contains("androidx.") &&
            !sourceText.contains("println("),
        "manifest=${manifestText.isNotEmpty()} source=${sourceText.isNotEmpty()}")

    val expected = buildFixture(dim, marker)
    var identical = true
    var firstDifference = ""
    for (name in ALL_FILES) {
        if (!committed.getValue(name).contentEquals(expected.files.getValue(name))) {
            identical = false
            firstDifference = name
            break
        }
    }
    audit.check("byte_identical_regeneration", identical, "files=${ALL_FILES.size} mismatch=$firstDifference")
    audit.printAllAndFinish()
}

fun main(args: Array<String>) {
    if (args.size < 2) {
        System.err.println("usage: Qa09DiagnosticsGate <generate|verify|mutate> <dir> [repoRoot|kind target]")
        exitProcess(2)
    }
    val command = args[0]
    val dir = File(args[1])
    try {
        when (command) {
            "generate" -> {
                val fixture = buildFixture(defaultDim(), markerFrom(SEED))
                writeFixture(dir, fixture)
                println("GENERATED\tfiles=${fixture.files.size}\tbytes=${fixture.files.values.sumOf { it.size }}")
            }
            "verify" -> {
                if (args.size < 3) fail("MISSING_REPO", "repoRoot argument required")
                verify(dir, File(args[2]))
            }
            "mutate" -> {
                if (args.size < 4) fail("MISSING_TARGET", "mutant target directory required")
                mutate(dir, File(args[3]), args[2], markerFrom(SEED))
            }
            else -> fail("BAD_COMMAND", command)
        }
    } catch (error: GateFailure) {
        println("CHECK\tFAIL\t${error.code}\t${error.detail}")
        println("FIRST\t${error.code}")
        println("SUMMARY\t0/1\tFAIL")
        exitProcess(1)
    } catch (error: Throwable) {
        println("ERROR\t${error.javaClass.simpleName}")
        println("FIRST\tUNEXPECTED_EXCEPTION")
        println("SUMMARY\t0/1\tFAIL")
        exitProcess(2)
    }
}
