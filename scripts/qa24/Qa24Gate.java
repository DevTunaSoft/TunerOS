    private static String sortedDigest(List<RawRow> rawRows) {
        List<Row> rows = parseAll(rawRows);
        Collections.sort(rows, rowComparator());
        return digest(serialize(rows).getBytes(StandardCharsets.UTF_8));
    }

    private static Map<String, byte[]> generate() {
        Map<String, byte[]> files = new LinkedHashMap<String, byte[]>();
        List<RawRow> rows = generateRows(MAX_ROWS);
        StringBuilder rowsText = new StringBuilder(HEADER).append('\n');
        for (RawRow row : rows) {
            rowsText.append(row.line()).append('\n');
        }
        files.put("contract.txt", utf8(contractText()));
        files.put("rows.tsv", utf8(rowsText.toString()));
        files.put("cases.tsv", utf8(casesText()));
        files.put("empty.tsv", utf8(HEADER + "\n"));
        files.put("single.tsv", utf8(HEADER + "\n" + rows.get(0).line() + "\n"));
        files.put("bad_header.tsv", utf8("id\tepoch\ttitle\tseason\tepisode\np00000\t1\tAlpha\t1\t1\n"));
        files.put("bad_fields.tsv", utf8(HEADER + "\np00000\t1\tAlpha\t1\n"));
        files.put("bad_id.tsv", utf8(HEADER + "\np.0000\t1\tAlpha\t1\t1\n"));
        files.put("bad_epoch.tsv", utf8(HEADER + "\np00000\t1x\tAlpha\t1\t1\n"));
        files.put("bad_number.tsv", utf8(HEADER + "\np00000\t1\tAlpha\t+1\t1\n"));
        files.put("oversize.tsv", utf8(HEADER + "\np00000\t1\tAlpha\t12345678901234567\t1\n"));

        StringBuilder manifest = new StringBuilder();
        for (String name : DATA_FILES) {
            manifest.append(digest(files.get(name))).append("  ").append(name).append('\n');
        }
        files.put("sha256.txt", utf8(manifest.toString()));

        StringBuilder dimensions = new StringBuilder(DIM_HEADER).append('\n');
        dimension(dimensions, "fixture_version", "1");
        dimension(dimensions, "large_rows", Integer.toString(MAX_ROWS));
        dimension(dimensions, "case_count", Integer.toString(CASES.length));
        dimension(dimensions, "sorted_sha256", sortedDigest(rows));
        dimension(dimensions, "manifest_sha256", digest(utf8(manifest.toString())));
        dimension(dimensions, "single_sha256", digest(files.get("single.tsv")));
        dimension(dimensions, "mirror_sha256", mirrorDigest());
        files.put("dimensions.tsv", utf8(dimensions.toString()));
        return files;
    }

    private static void dimension(StringBuilder out, String key, String value) {
        out.append(key).append('\t').append(value).append('\n');
    }

    private static boolean coveragePresent(List<RawRow> rows) {
        int unknown = 0;
        int clipped = 0;
        int prefixed = 0;
        int padded = 0;
        for (RawRow row : rows) {
            if (row.season.isEmpty() || row.episode.isEmpty()) {
                unknown++;
            }
            if (row.season.startsWith("1000") || row.episode.startsWith("1000")) {
                clipped++;
            }
            if (row.season.matches("(?i)[se].*") || row.episode.matches("(?i)[se].*")) {
                prefixed++;
            }
            if (row.season.indexOf(' ') >= 0 || row.episode.indexOf(' ') >= 0) {
                padded++;
            }
        }
        return unknown > 0 && clipped > 0 && prefixed > 0 && padded > 0;
    }

    private static String mirrorDigest() {
        List<RawRow> rows = generateRows(MIRROR_ROWS);
        List<Row> parsed = parseAll(rows);
        Collections.sort(parsed, rowComparator());
        return digest(serialize(parsed).getBytes(StandardCharsets.UTF_8));
    }

    private static Num parseNumber(String raw, char prefix) {
        if (raw == null) {
            throw bad("BAD_NUMBER");
        }
        if (raw.length() > MAX_RAW_LEN) {
            throw bad("ROW_BOUNDS");
        }
        String text = raw.trim();
        if (text.isEmpty()) {
            return new Num(UNKNOWN, false);
        }
        char first = text.charAt(0);
        if (first == prefix || first == Character.toUpperCase(prefix)) {
            text = text.substring(1).trim();
            if (text.isEmpty()) {
                throw bad("BAD_NUMBER");
            }
        }
        int firstDigit = 0;
        while (firstDigit < text.length() && text.charAt(firstDigit) == '0') {
            firstDigit++;
        }
        String digits = text.substring(firstDigit);
        if (digits.isEmpty()) {
            return new Num(0, false);
        }
        if (digits.length() > MAX_DIGITS) {
            throw bad("OVERFLOW");
        }
        for (int i = 0; i < digits.length(); i++) {
            char c = digits.charAt(i);
            if (c < '0' || c > '9') {
                throw bad("BAD_NUMBER");
            }
        }
        long value = Long.parseLong(digits);
        if (value > CLIP_MAX) {
            return new Num((int) CLIP_MAX, true);
        }
        return new Num((int) value, false);
    }

    private static String normalizeTitle(String raw) {
        if (raw == null || raw.length() > MAX_TITLE_LEN) {
            throw bad("ROW_BOUNDS");
        }
        StringBuilder out = new StringBuilder(raw.length());
        boolean pending = false;
        for (int i = 0; i < raw.length(); i++) {
            char c = raw.charAt(i);
            if (c < 0x20 || c == 0x7F) {
                throw bad("BAD_TITLE");
            }
            if (Character.isWhitespace(c)) {
                pending = out.length() > 0;
                continue;
            }
            if (pending) {
                out.append(' ');
                pending = false;
            }
            out.append(Character.toLowerCase(c));
        }
        if (out.length() == 0) {
            throw bad("BAD_TITLE");
        }
        return out.toString();
    }

    private static int orderKey(int value) {
        return value == UNKNOWN ? Integer.MAX_VALUE : value;
    }

    private static Comparator<Row> rowComparator() {
        return new Comparator<Row>() {
            @Override
            public int compare(Row a, Row b) {
                int result = Long.compare(a.epoch, b.epoch);
                if (result != 0) {
                    return result;
                }
                result = Integer.compare(orderKey(a.season), orderKey(b.season));
                if (result != 0) {
                    return result;
                }
                result = Integer.compare(orderKey(a.episode), orderKey(b.episode));
                if (result != 0) {
                    return result;
                }
                result = a.titleKey.compareTo(b.titleKey);
                if (result != 0) {
                    return result;
                }
                return a.id.compareTo(b.id);
            }
        };
    }

    private static String serialize(List<Row> rows) {
        StringBuilder out = new StringBuilder();
        for (Row row : rows) {
            out.append(row.id).append('|').append(row.epoch).append('|')
                .append(row.season).append('|').append(row.episode).append('|')
                .append(row.titleKey).append('\n');
        }
        return out.toString();
    }

    private static Row toRow(RawRow raw) {
        long epoch = Long.parseLong(raw.epoch);
        if (epoch > MAX_EPOCH) {
            throw bad("BAD_EPOCH");
        }
        Num season = parseNumber(raw.season, 's');
        Num episode = parseNumber(raw.episode, 'e');
        return new Row(raw.id, epoch, normalizeTitle(raw.title), season.value, episode.value);
    }

    private static List<Row> parseAll(List<RawRow> rawRows) {
        List<Row> rows = new ArrayList<Row>(rawRows.size());
        for (RawRow raw : rawRows) {
            rows.add(toRow(raw));
        }
        return rows;
    }

    private static List<RawRow> parseRows(String text) {
        String[] lines = text.split("\n", -1);
        int length = lines.length;
        if (length > 0 && lines[length - 1].isEmpty()) {
            length--;
        }
        if (length == 0 || !HEADER.equals(lines[0])) {
            throw bad("MALFORMED_HEADER");
        }
        if (length == 1) {
            throw bad("EMPTY_INPUT");
        }
        List<RawRow> rows = new ArrayList<RawRow>(length - 1);
        for (int i = 1; i < length; i++) {
            String line = lines[i];
            if (line.isEmpty() || line.length() > MAX_LINE_LEN) {
                throw bad("ROW_BOUNDS");
            }
            String[] fields = line.split("\t", -1);
            if (fields.length != 5) {
                throw bad("ROW_BOUNDS");
            }
            if (!ID_PATTERN.matcher(fields[0]).matches()) {
                throw bad("BAD_ID");
            }
            if (!EPOCH_PATTERN.matcher(fields[1]).matches()) {
                throw bad("BAD_EPOCH");
            }
            rows.add(new RawRow(fields[0], fields[1], fields[2], fields[3], fields[4]));
        }
        parseAll(rows);
        return rows;
    }

    private static final class Gate {
        final StringBuilder report = new StringBuilder();
        String first;
        int pass;
        int fail;

        void record(String id, boolean ok) {
            if (ok) {
                pass++;
                report.append("CHECK\t").append(id).append("\tPASS\n");
            } else {
                fail++;
                report.append("CHECK\t").append(id).append("\tFAIL\n");
                if (first == null) {
                    first = id;
                }
            }
        }

        void expectReject(String id, String expected, Runnable action) {
            try {
                action.run();
                record(id, false);
            } catch (GateFailure failure) {
                record(id, expected.equals(failure.code));
            } catch (RuntimeException failure) {
                record(id, false);
            }
        }

        void checkCase(CaseSpec spec) {
            try {
                Num parsed = parseNumber(spec.raw, spec.season ? 's' : 'e');
                record("CASE_" + spec.id, "ACCEPT".equals(spec.expect)
                    && parsed.value == spec.value && parsed.clipped == spec.clipped);
            } catch (GateFailure failure) {
                record("CASE_" + spec.id, spec.expect.equals(failure.code));
            }
        }

        void print() {
            System.out.print(report);
            System.out.println("FIRST\t" + (first == null ? "NONE" : first));
            System.out.println("SUMMARY\tpass=" + pass + "\tfail=" + fail);
            System.out.println("RESULT\t" + (fail == 0 ? "PASS" : "FAIL"));
        }
    }

    private static String read(Map<String, byte[]> files, String name) {
        byte[] bytes = files.get(name);
        if (bytes == null) {
            throw bad("MISSING_FILE");
        }
        return new String(bytes, StandardCharsets.UTF_8);
    }

    private static boolean privacyClean(String text) {
        if (ADDRESS_PATTERN.matcher(text).find()
            || SENSITIVE_PATTERN.matcher(text).find()
            || text.contains(marker())
            || text.contains(derivedToken())) {
            return false;
        }
        return true;
    }

    private static Map<String, String> parsePairs(String text, String header) {
        String[] lines = text.split("\n", -1);
        if (lines.length == 0 || !header.equals(lines[0])) {
            throw bad("MALFORMED_HEADER");
        }
        Map<String, String> pairs = new LinkedHashMap<String, String>();
        for (int i = 1; i < lines.length; i++) {
            if (lines[i].isEmpty()) {
                continue;
            }
            String[] fields = lines[i].split("\t", -1);
            if (fields.length != 2) {
                throw bad("ROW_BOUNDS");
            }
            pairs.put(fields[0], fields[1]);
        }
        return pairs;
    }

    private static Map<String, String> parseManifest(String text) {
        String[] lines = text.split("\n", -1);
        Map<String, String> pairs = new LinkedHashMap<String, String>();
        for (String line : lines) {
            if (line.isEmpty()) {
                continue;
            }
            String[] fields = line.split("  ", -1);
            if (fields.length != 2 || fields[0].length() != 64) {
                throw bad("MALFORMED_HEADER");
            }
            pairs.put(fields[1], fields[0]);
        }
        return pairs;
    }

    private static long usedHeap() {
        Runtime runtime = Runtime.getRuntime();
        return runtime.totalMemory() - runtime.freeMemory();
    }

    private static void settle() {
        System.gc();
        try {
            Thread.sleep(20L);
        } catch (InterruptedException error) {
            Thread.currentThread().interrupt();
        }
    }

    private static void boundedResources(Gate gate, String rowsText) {
        long baseline = 0L;
        long peak = 0L;
        int threads = 0;
        for (int cycle = 0; cycle < HEAP_CYCLES; cycle++) {
            List<Row> rows = parseAll(parseRows(rowsText));
            Collections.sort(rows, rowComparator());
            sink += rows.size();
            settle();
            if (cycle == 0) {
                baseline = usedHeap();
            }
            peak = Math.max(peak, usedHeap());
            threads = Math.max(threads, Thread.activeCount());
            rows = null;
        }
        settle();
        boolean named = false;
        for (Thread thread : Thread.getAllStackTraces().keySet()) {
            if (thread.getName().startsWith("qa24-")) {
                named = true;
            }
        }
        gate.record("HEAP_THREADS_BOUNDED", peak <= baseline + MAX_HEAP_GROWTH
            && threads <= MAX_THREADS && !named);
    }

    private static Gate runVerify(Path dir, boolean semantic) throws IOException {
        Gate gate = new Gate();
        Map<String, byte[]> committed = new LinkedHashMap<String, byte[]>();
        for (String name : ALL_FILES) {
            Path file = dir.resolve(name);
            if (!Files.isRegularFile(file)) {
                throw bad("MISSING_FILE");
            }
            committed.put(name, Files.readAllBytes(file));
        }
        Map<String, byte[]> expected = generate();
        if (!semantic) {
            boolean identical = true;
            for (String name : ALL_FILES) {
                if (!java.util.Arrays.equals(expected.get(name), committed.get(name))) {
                    identical = false;
                }
            }
            gate.record("FIXTURE_BYTE_IDENTICAL", identical);
        }

        Map<String, String> manifest = parseManifest(read(committed, "sha256.txt"));
        boolean manifestOk = true;
        for (String name : DATA_FILES) {
            String listed = manifest.get(name);
            if (listed == null || !listed.equals(digest(committed.get(name)))) {
                manifestOk = false;
            }
        }
        gate.record("MANIFEST_SHA256", manifestOk);

        if (!semantic) {
            gate.record("MANIFEST_PINNED", MANIFEST_DIGEST_PIN.equals(digest(committed.get("sha256.txt"))));
            Map<String, String> dimensions = parsePairs(read(committed, "dimensions.tsv"), DIM_HEADER);
            gate.record("DIMENSIONS_PINNED", "1".equals(dimensions.get("fixture_version"))
                && Integer.toString(MAX_ROWS).equals(dimensions.get("large_rows"))
                && Integer.toString(CASES.length).equals(dimensions.get("case_count"))
                && SORTED_DIGEST_PIN.equals(dimensions.get("sorted_sha256"))
                && MANIFEST_DIGEST_PIN.equals(dimensions.get("manifest_sha256"))
                && SINGLE_DIGEST_PIN.equals(dimensions.get("single_sha256"))
                && MIRROR_DIGEST_PIN.equals(dimensions.get("mirror_sha256")));
        }

        String rowsText = read(committed, "rows.tsv");
        String headerActual = rowsText.split("\n", -1)[0];
        gate.record("HEADER_STRICT", HEADER.equals(headerActual)
            && CASE_HEADER.equals(read(committed, "cases.tsv").split("\n", -1)[0]));
        gate.record("CASE_COVERAGE", coveragePresent(parseRows(rowsText)));

        for (CaseSpec spec : CASES) {
            gate.checkCase(spec);
        }

        gate.expectReject("EMPTY_REJECT", "EMPTY_INPUT", new Runnable() {
            @Override
            public void run() {
                parseRows(read(committed, "empty.tsv"));
            }
        });
        gate.expectReject("SINGLE_OK", "SINGLE_ACCEPT", new Runnable() {
            @Override
            public void run() {
                List<RawRow> single = parseRows(read(committed, "single.tsv"));
                if (single.size() != 1) {
                    throw bad("SINGLE_REJECT");
                }
                throw bad("SINGLE_ACCEPT");
            }
        });
        String[][] malformed = {
            {"bad_header.tsv", "MALFORMED_HEADER"},
            {"bad_fields.tsv", "ROW_BOUNDS"},
            {"bad_id.tsv", "BAD_ID"},
            {"bad_epoch.tsv", "BAD_EPOCH"},
            {"bad_number.tsv", "BAD_NUMBER"},
            {"oversize.tsv", "ROW_BOUNDS"}
        };
        for (final String[] entry : malformed) {
            gate.expectReject("MALFORMED_" + entry[0], entry[1], new Runnable() {
                @Override
                public void run() {
                    parseRows(read(committed, entry[0]));
                }
            });
        }

        StringBuilder scanText = new StringBuilder(gate.report);
        for (Map.Entry<String, byte[]> entry : committed.entrySet()) {
            scanText.append(new String(entry.getValue(), StandardCharsets.ISO_8859_1)).append('\n');
        }
        // Semantic mutants may add one extra scratch file; include it in the leak scan.
        File[] extra = dir.toFile().listFiles();
        if (extra != null) {
            for (File file : extra) {
                if (file.isFile() && !committed.containsKey(file.getName())) {
                    try {
                        scanText.append(new String(Files.readAllBytes(file.toPath()),
                            StandardCharsets.ISO_8859_1)).append('\n');
                    } catch (IOException error) {
                        scanText.append("READ_FAILURE\n");
                    }
                }
            }
        }
        gate.record("PRIVACY_SCAN", privacyClean(scanText.toString()));

        List<Row> sorted = parseAll(parseRows(rowsText));
        Comparator<Row> comparator = rowComparator();
        Collections.sort(sorted, comparator);
        boolean ordered = sorted.size() == MAX_ROWS;
        for (int i = 1; i < sorted.size() && ordered; i++) {
            if (comparator.compare(sorted.get(i - 1), sorted.get(i)) > 0) {
                ordered = false;
            }
        }
        gate.record("SORT_ORDER", ordered && SORTED_DIGEST_PIN.equals(digest(serialize(sorted).getBytes(StandardCharsets.UTF_8))));
        gate.record("MIRROR_DIGEST", MIRROR_DIGEST_PIN.equals(mirrorDigest()));
        boundedResources(gate, rowsText);
        gate.print();
        return gate;
    }

    public static void main(String[] args) throws Exception {
        if (args.length < 1) {
            throw bad("USAGE");
        }
        String mode = args[0];
        if ("marker".equals(mode)) {
            System.out.print(marker());
            return;
        }
        if (args.length < 2) {
            throw bad("USAGE");
        }
        Path dir = Paths.get(args[1]);
        if ("generate".equals(mode)) {
            Files.createDirectories(dir);
            Map<String, byte[]> files = generate();
            for (Map.Entry<String, byte[]> entry : files.entrySet()) {
                Files.write(dir.resolve(entry.getKey()), entry.getValue());
            }
            System.out.println("GENERATE\tfiles=" + files.size() + "\trows=" + MAX_ROWS);
            return;
        }
        if ("verify".equals(mode)) {
            try {
                Gate gate = runVerify(dir, args.length > 2 && "semantic".equals(args[2]));
                if (gate.fail > 0) {
                    System.exit(1);
                }
            } catch (GateFailure failure) {
                System.out.println("CHECK\tSTRUCTURAL\tFAIL");
                System.out.println("FIRST\t" + failure.code);
                System.out.println("SUMMARY\tpass=0\tfail=1");
                System.out.println("RESULT\tFAIL");
                System.exit(1);
            }
            return;
        }
        throw bad("USAGE");
    }
