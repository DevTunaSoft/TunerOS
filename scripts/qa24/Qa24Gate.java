    private static long next(long[] state) {
        state[0] = state[0] * 6364136223846793005L + 1442695040888963407L;
        return (state[0] >>> 17) & 0x7fffffffL;
    }

    private static String pad(int value, int width) {
        String text = Integer.toString(value);
        StringBuilder out = new StringBuilder(width);
        for (int i = text.length(); i < width; i++) {
            out.append('0');
        }
        return out.append(text).toString();
    }

    private static String numberForm(int value, int form, boolean season) {
        String base = Integer.toString(value);
        switch (form) {
            case 0:
                return base;
            case 1:
                return (season ? "S" : "E") + base;
            case 2:
                return pad(value, 3);
            case 3:
                return " " + base + " ";
            case 5:
                return Integer.toString(10000 + value % 3);
            default:
                return "";
        }
    }

    private static List<RawRow> generateRows(int count) {
        long[] state = {SEED};
        List<RawRow> rows = new ArrayList<RawRow>(count);
        for (int i = 0; i < count; i++) {
            long v0 = next(state);
            long v1 = next(state);
            long v2 = next(state);
            long v3 = next(state);
            long epoch = 1_700_000_000L + (v0 % 400L);
            String title = TITLES[(int) (v1 % TITLES.length)];
            switch ((int) (v2 % 4L)) {
                case 0:
                    break;
                case 1:
                    title = "  " + title + "  ";
                    break;
                case 2:
                    title = title.toUpperCase(Locale.ROOT);
                    break;
                default:
                    title = title + "   " + title;
                    break;
            }
            String season = numberForm((int) (v1 % 14L), (int) (v3 % 6L), true);
            String episode = numberForm((int) (v2 % 20L), (int) ((v3 >>> 8) % 6L), false);
            rows.add(new RawRow("p" + pad(i, 5), Long.toString(epoch), title, season, episode));
        }
        return rows;
    }

    private static String digest(byte[] bytes) {
        try {
            byte[] raw = MessageDigest.getInstance("SHA-256").digest(bytes);
            StringBuilder out = new StringBuilder(raw.length * 2);
            for (byte value : raw) {
                int word = value & 0xFF;
                out.append(HEX[word >>> 4]).append(HEX[word & 0xF]);
            }
            return out.toString();
        } catch (NoSuchAlgorithmException error) {
            throw new IllegalStateException("DIGEST_UNAVAILABLE");
        }
    }

    private static byte[] utf8(String text) {
        return text.getBytes(StandardCharsets.UTF_8);
    }

    private static String marker() {
        char[] chars = new char[12];
        long value = SEED ^ 0x5A5A5A5AL;
        for (int i = 0; i < chars.length; i++) {
            value = value * 31L + i + 7L;
            chars[i] = (char) ('a' + Math.floorMod(value, 26L));
        }
        return new String(chars);
    }

    private static String derivedToken() {
        long value = SEED * 2862933555777941757L + 3037000493L;
        StringBuilder out = new StringBuilder(16);
        for (int i = 0; i < 16; i++) {
            value = value * 6364136223846793005L + 1442695040888963407L;
            out.append(HEX[(int) ((value >>> 60) & 0xFL)]);
        }
        return out.toString();
    }

