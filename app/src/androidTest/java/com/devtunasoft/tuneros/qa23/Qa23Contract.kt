package com.devtunasoft.tuneros.qa23

import com.devtunasoft.tuneros.core.DashSegmentIndex
import com.devtunasoft.tuneros.core.HlsByteRange
import java.nio.ByteBuffer
import java.security.MessageDigest

/**
 * Android-free QA-23 mirror. Generates sidx bytes in memory from constants and runs
 * them through the same production DashSegmentIndex the host gate compiles. No fixture
 * file I/O, no Android imports, so the same source runs on the JVM and on the device.
 */
object Qa23Contract {
    const val SEED = 20261123L
    const val MIRROR_REFS = 256
    const val MIRROR_RANGE_OFFSET = 8_192L
    // Pinned from the mirror generator; a change in generated bytes fails MIRROR_DIGEST.
    const val MIRROR_DIGEST = "daf2eccd039f2e750275a67b2b819ae0e1c02901051b4c9e77cc10874ebb327b"

    private fun be16(value: Int): ByteArray = ByteBuffer.allocate(2).putShort(value.toShort()).array()
    private fun be32(value: Long): ByteArray = ByteBuffer.allocate(4).putInt(value.toInt()).array()
    private fun be64(value: Long): ByteArray = ByteBuffer.allocate(8).putLong(value).array()

    private data class Ref(val length: Long, val duration: Long, val hierarchical: Boolean = false)

    private data class Spec(
        val version: Int,
        val timescale: Long,
        val firstOffset: Long,
        val refs: List<Ref>,
        val type: String = "sidx",
        val versionField: Int = version,
        val countOverride: Int? = null,
        val sizeField: Int? = null,
    )

    private fun box(spec: Spec): ByteArray {
        val header = if (spec.version == 0) 32 else 40
        val count = spec.countOverride ?: spec.refs.size
        val declared = spec.sizeField?.toLong() ?: (header.toLong() + 12L * count)
        val actual = header + 12 * spec.refs.size
        val out = ByteBuffer.allocate(actual)
        out.put(be32(declared))
        out.put(spec.type.toByteArray(Charsets.US_ASCII))
        out.put(spec.versionField.toByte())
        out.put(byteArrayOf(0, 0, 0))
        out.put(be32(1L))
        out.put(be32(spec.timescale))
        if (spec.version == 0) {
            out.put(be32(0L))
            out.put(be32(spec.firstOffset))
        } else {
            out.put(be64(0L))
            out.put(be64(spec.firstOffset))
        }
        out.put(be16(0))
        out.put(be16(count))
        for (ref in spec.refs) {
            val word = (if (ref.hierarchical) 0x8000_0000L else 0L) or ref.length
            out.put(be32(word))
            out.put(be32(ref.duration))
            out.put(be32(0L))
        }
        return out.array()
    }

    private fun digest(bytes: ByteArray): String {
        val hex = "0123456789abcdef"
        return MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { value ->
            val word = value.toInt() and 0xFF
            "" + hex[word ushr 4] + hex[word and 0xF]
        }
    }

    private fun modelDigest(timescale: Long, refs: List<Triple<Long, Long, Long>>): String {
        val text = StringBuilder().append(timescale).append('\n')
        for (ref in refs) text.append(ref.first).append('|').append(ref.second).append('|').append(ref.third).append('\n')
        return digest(text.toString().toByteArray(Charsets.UTF_8))
    }

    private fun mirrorLarge(): ByteArray = box(
        Spec(0, 90_000L, 0L, List(MIRROR_REFS) { Ref(1_000L, 1_000L) }),
    )

    private fun mirrorDigest(): String {
        val large = mirrorLarge()
        var offset = MIRROR_RANGE_OFFSET + large.size.toLong()
        val triples = ArrayList<Triple<Long, Long, Long>>(MIRROR_REFS)
        repeat(MIRROR_REFS) {
            triples += Triple(offset, 1_000L, 1_000L)
            offset += 1_000L
        }
        return modelDigest(90_000L, triples)
    }

    private fun parse(bytes: ByteArray, offset: Long, length: Long): DashSegmentIndex.Outcome =
        DashSegmentIndex.parse(bytes, HlsByteRange(length = length, offset = offset))

    fun runChecks(): List<String> {
        val lines = mutableListOf<String>()
        fun check(id: String, ok: Boolean) {
            lines.add(if (ok) "CHECK\tPASS\t$id" else "CHECK\tFAIL\t$id")
        }

        val v0 = box(Spec(0, 90_000L, 1_024L, listOf(Ref(4_000L, 3_000L), Ref(4_001L, 3_000L), Ref(4_002L, 3_000L))))
        val v0Outcome = parse(v0, 4_096L, v0.size.toLong())
        val v0Ok = v0Outcome is DashSegmentIndex.Outcome.Parsed &&
            v0Outcome.timescale == 90_000L && v0Outcome.references.size == 3 &&
            v0Outcome.references[0].range.offset == 4_096L + v0.size.toLong() + 1_024L &&
            v0Outcome.references[0].range.length == 4_000L &&
            v0Outcome.references[2].durationTicks == 3_000L
        check("MIRROR_VALID_V0", v0Ok)

        val v1 = box(Spec(1, 48_000L, 2_048L, listOf(Ref(2_000L, 1_500L), Ref(2_001L, 1_500L))))
        val v1Outcome = parse(v1, 4_096L, v1.size.toLong())
        val v1Ok = v1Outcome is DashSegmentIndex.Outcome.Parsed &&
            v1Outcome.timescale == 48_000L && v1Outcome.references.size == 2 &&
            v1Outcome.references[1].range.length == 2_001L
        check("MIRROR_VALID_V1", v1Ok)

        fun refused(spec: Spec, offset: Long = 4_096L, length: Long? = null): Boolean {
            val bytes = box(spec)
            val outcome = parse(bytes, offset, length ?: bytes.size.toLong())
            return outcome is DashSegmentIndex.Outcome.Refused
        }
        check(
            "MIRROR_VERSION_REJECT",
            refused(Spec(0, 90_000L, 0L, listOf(Ref(100L, 100L)), versionField = 2)),
        )
        check(
            "MIRROR_HIER_REJECT",
            refused(Spec(0, 90_000L, 0L, listOf(Ref(100L, 100L, hierarchical = true)))),
        )
        check(
            "MIRROR_EMPTY_REJECT",
            refused(Spec(0, 90_000L, 0L, listOf(Ref(0L, 100L)))),
        )
        check(
            "MIRROR_ZERO_DUR_REJECT",
            refused(Spec(0, 90_000L, 0L, listOf(Ref(100L, 0L)))),
        )
        check(
            "MIRROR_TRUNCATED_REJECT",
            refused(
                Spec(0, 90_000L, 0L, listOf(Ref(100L, 100L), Ref(100L, 100L)), countOverride = 3, sizeField = 56),
            ),
        )

        val large = mirrorLarge()
        val startThreads = Thread.activeCount()
        var bounded = true
        var digestOk = true
        repeat(3) {
            val outcome = parse(large, MIRROR_RANGE_OFFSET, large.size.toLong())
            if (outcome !is DashSegmentIndex.Outcome.Parsed) {
                bounded = false
            } else {
                digestOk = digestOk && outcome.references.size == MIRROR_REFS
            }
            System.gc()
            Thread.sleep(20)
            bounded = bounded && Thread.activeCount() <= startThreads + 2
        }
        check("MIRROR_BOUNDED", bounded && digestOk && mirrorDigest() == MIRROR_DIGEST)
        return lines
    }

    @JvmStatic
    fun main(args: Array<String>) {
        println("MIRROR_DIGEST\t${mirrorDigest()}")
        for (line in runChecks()) println(line)
    }
}
