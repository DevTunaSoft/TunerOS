    fun embeddedFixture(): String = EMBEDDED.lineSequence()
        .filter { it != FIXTURE_BEGIN && it != FIXTURE_END }
        .joinToString("\n", postfix = "\n")

    fun runAll(fixtureText: String = embeddedFixture()): List<Qa05Result> {
        val parsed = parse(fixtureText)
        val results = ArrayList<Qa05Result>()
        fun check(id: String, passed: Boolean, detail: String) {
            results += Qa05Result(id, passed, detail)
        }

        check("fixture-version", parsed.version == 1, "version=${parsed.version}")
        check("fixture-window", parsed.windowTo > parsed.windowFrom,
            "from=${parsed.windowFrom} to=${parsed.windowTo}")
        val uniqueIds = parsed.channels.map { it.id }.toSet().size == parsed.channels.size
        check("fixture-unique-channel-ids", uniqueIds && parsed.channels.size == 5,
            "channels=${parsed.channels.size}")
        val guideIds = parsed.channels.mapNotNull { it.guideId }.toSet()
        val knownGuides = parsed.programmes.all { it.channelId in guideIds }
        check("fixture-known-guide-ids", knownGuides && parsed.programmes.size == 5,
            "programmes=${parsed.programmes.size}")

        for (expect in parsed.expects) {
            val actual = visible(parsed, true, expect.query, expect.hide)
            check("filter-${expect.id}", actual == expect.expected,
                "query=[${expect.query}] hide=${expect.hide} expected=${expect.expected} actual=$actual")
        }
        for (noGuide in parsed.noGuides) {
            val actual = visible(parsed, false, noGuide.query, true)
            check("noguide-${noGuide.id}", actual == noGuide.expected,
                "query=[${noGuide.query}] no guide snapshot, hide=true, actual=$actual")
        }
        for (view in parsed.views) {
            val rows = visible(parsed, true, view.query, view.hide)
            check("view-${view.id}", rows == view.rows,
                "rows=$rows expected=${view.rows}; each bound row has one channel cell and one timeline")
        }
        for (bound in parsed.bounds) {
            val rows = visible(parsed, true, bound.query, bound.hide).size
            check("bound-${bound.id}", rows == bound.cells && rows == bound.timelines,
                "rows=$rows cells=${bound.cells} timelines=${bound.timelines}")
        }

        val hiddenRows = visible(parsed, true, "", true)
        for (focus in parsed.focuses) {
            val channel = parsed.channels.firstOrNull { it.id == focus.channel }
            if (channel == null) {
                check("focus-${focus.id}", false, "unknown channel ${focus.channel}")
                continue
            }
            val bound = focus.channel in hiddenRows
            val entries = channel.guideId?.let { entriesFor(parsed, it, focus.from, focus.to) } ?: emptyList()
            val preferred = preferredIndex(entries)
            val title = if (preferred < 0) "none" else entries[preferred].title ?: "none"
            val contiguous = entries.isEmpty() ||
                (entries.first().start == focus.from && entries.last().end == focus.to && covers(focus, entries))
            check("focus-${focus.id}",
                bound == focus.cellBound && preferred == focus.index && title == focus.title && contiguous,
                "cellBound=$bound expected=${focus.cellBound} preferredIndex=$preferred expected=${focus.index} " +
                    "label=$title contiguous=$contiguous")
        }
        for (nav in parsed.navRights) {
            val entries = navigationEntries(nav.channel, nav.from, nav.to, parsed)
            if (entries == null) {
                check("nav-${nav.id}", false, "unknown channel or no guide id: ${nav.channel}")
                continue
            }
            val right = nextIndex(entries, nav.start, 1)
            val back = nextIndex(entries, right, -1)
            check("nav-${nav.id}", right == nav.right && back == nav.back,
                "from=${nav.start} RIGHT=$right LEFT-from-right=$back; no window shift between programmes")
        }
        for (nav in parsed.navEdges) {
            val entries = navigationEntries(nav.channel, nav.from, nav.to, parsed)
            if (entries == null) {
                check("nav-${nav.id}", false, "unknown channel or no guide id: ${nav.channel}")
                continue
            }
            val left = nextIndex(entries, nav.start, -1)
            val shift = if (left < 0) -1 else 0
            check("nav-${nav.id}", left == nav.left && shift == nav.shiftDirection,
                "LEFT from first programme=$left expected=${nav.left} window shift=$shift expected=${nav.shiftDirection}")
        }
        return results
    }

    private fun navigationEntries(
        channelId: String, from: Long, to: Long, parsed: Parsed,
    ): List<Qa05Entry>? {
        val guideId = parsed.channels.firstOrNull { it.id == channelId }?.guideId ?: return null
        return entriesFor(parsed, guideId, from, to)
    }

    /** Mirrors core ChannelVisibility.filter: trimmed case-insensitive name search and hide-no-EPG. */
    private fun visible(fixture: Parsed, guidePresent: Boolean, query: String, hide: Boolean): List<String> {
        val search = query.trim()
        if (search.isEmpty() && !hide) return fixture.channels.map { it.id }
        if (hide && !guidePresent) return emptyList()
        val needle = search.lowercase()
        return fixture.channels.filter { channel ->
            val nameMatches = search.isEmpty() || channel.name.lowercase().contains(needle)
            val hasSchedule = channel.guideId?.let { id -> fixture.programmes.any { it.channelId == id } } == true
            nameMatches && (!hide || hasSchedule)
        }.map { it.id }
    }

    /** Mirrors core TimelineLayout.rowFromSorted: contiguous clipped programmes and gaps. */
    private fun entriesFor(fixture: Parsed, guideId: String, from: Long, to: Long): List<Qa05Entry> {
        val sorted = fixture.programmes
            .filter { it.channelId == guideId && it.end > from && it.start < to }
            .sortedWith(compareBy<Qa05Programme> { it.start }.thenBy { it.end })
        val entries = ArrayList<Qa05Entry>()
        var cursor = from
        for (programme in sorted) {
            if (programme.start >= to) break
            val start = maxOf(programme.start, from, cursor)
            val end = minOf(programme.end, to)
            if (end <= start) continue
            if (start > cursor) entries += Qa05Entry(cursor, start, null)
            entries += Qa05Entry(start, end, programme.title)
            cursor = end
            if (cursor >= to) break
        }
        if (cursor < to) entries += Qa05Entry(cursor, to, null)
        return entries
    }

    /** Mirrors core TimelineFocusPolicy: gaps are never selectable. */
    private fun preferredIndex(entries: List<Qa05Entry>): Int =
        entries.indexOfFirst { !it.isGap }

    private fun nextIndex(entries: List<Qa05Entry>, current: Int, direction: Int): Int {
        var index = current + direction
        while (index in entries.indices) {
            if (!entries[index].isGap) return index
            index += direction
        }
        return -1
    }

    private fun covers(focus: Focus, entries: List<Qa05Entry>): Boolean {
        var cursor = focus.from
        for (entry in entries) {
            if (entry.start != cursor || entry.end <= entry.start) return false
            cursor = entry.end
        }
        return cursor == focus.to
    }

    private fun parse(text: String): Parsed {
        val channels = ArrayList<Qa05Channel>()
        val programmes = ArrayList<Qa05Programme>()
        val expects = ArrayList<Expect>()
        val noGuides = ArrayList<NoGuide>()
        val views = ArrayList<View>()
        val bounds = ArrayList<Bound>()
        val focuses = ArrayList<Focus>()
        val navRights = ArrayList<NavRight>()
        val navEdges = ArrayList<NavEdge>()
        var version = -1
        var windowFrom = 0L
        var windowTo = 0L
        for (raw in text.lineSequence()) {
            val line = raw.trim()
            if (line.isEmpty() || line.startsWith("#")) continue
            val p: List<String>
            if (line.startsWith("VERSION ") || line.startsWith("WINDOW ")) {
                val words = line.split(Regex("\\s+"))
                if (words[0] == "VERSION") version = words[1].toInt()
                else {
                    windowFrom = words[1].toLong()
                    windowTo = words[2].toLong()
                }
                continue
            }
            // The record kind is separated from its first field by a space, later fields by '|'.
            val space = line.indexOf(' ')
            val normalized = if (space < 0) line else line.substring(0, space) + "|" + line.substring(space + 1)
            p = normalized.split("|")
            when (p[0]) {
                "CHANNEL" -> channels += Qa05Channel(
                    p[1], p[2], p[3].ifEmpty { null }, p[4],
                )
                "PROGRAMME" -> programmes += Qa05Programme(
                    p[1], p[2], p[3].toLong(), p[4].toLong(),
                )
                "EXPECT" -> expects += Expect(p[1], unempty(p[2]), p[3].toBoolean(), ids(p[4]))
                "NOGUIDE" -> noGuides += NoGuide(p[1], unempty(p[2]), ids(p[3]))
                "VIEW" -> views += View(p[1], unempty(p[2]), p[3].toBoolean(), ids(p[4]))
                "BOUND" -> bounds += Bound(
                    p[1], unempty(p[2]), p[3].toBoolean(), p[4].toInt(), p[5].toInt(),
                )
                "FOCUS" -> focuses += Focus(
                    p[1], p[2].toLong(), p[3].toLong(), p[4], p[5].toInt(), unempty(p[6]), p[7].toBoolean(),
                )
                "NAVRIGHT" -> navRights += NavRight(
                    p[1], p[2].toLong(), p[3].toLong(), p[4],
                    p[5].toInt(), p[6].toInt(), p[7].toInt(),
                )
                "NAVEDGE" -> navEdges += NavEdge(
                    p[1], p[2].toLong(), p[3].toLong(), p[4],
                    p[5].toInt(), p[6].toInt(), p[7].toInt(),
                )
                else -> throw IllegalArgumentException("unknown fixture record: ${p[0]}")
            }
        }
        return Parsed(version, windowFrom, windowTo, channels, programmes, expects,
            noGuides, views, bounds, focuses, navRights, navEdges)
    }

    private fun unempty(token: String): String = if (token == "(empty)") "" else token

    private fun ids(token: String): List<String> = if (token == "(none)") emptyList() else token.split(",")

    @JvmStatic
    fun main(args: Array<String>) {
        val text = if (args.isEmpty()) embeddedFixture() else File(args[0]).readText()
        val results = runAll(text)
        results.forEach { println("${if (it.passed) "PASS" else "FAIL"}\t${it.id}\t${it.detail}") }
        val failures = results.count { !it.passed }
        println("QA05 KOTLIN ASSERTIONS ${if (failures == 0) "PASS" else "FAIL"}: " +
            "${results.size - failures}/${results.size} checks")
        if (failures > 0) exitProcess(1)
    }
}
