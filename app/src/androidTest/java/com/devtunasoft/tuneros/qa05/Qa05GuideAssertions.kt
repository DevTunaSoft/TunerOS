package com.devtunasoft.tuneros.qa05

import java.io.File
import kotlin.system.exitProcess

/** Scratch fixture records. No provider URL, credential or real media is represented here. */
data class Qa05Channel(val id: String, val name: String, val guideId: String?, val streamRef: String)
data class Qa05Programme(val channelId: String, val title: String, val start: Long, val end: Long)
data class Qa05Entry(val start: Long, val end: Long, val title: String?) {
    val isGap: Boolean get() = title == null
}
data class Qa05Result(val id: String, val passed: Boolean, val detail: String)

private data class Expect(val id: String, val query: String, val hide: Boolean, val expected: List<String>)
private data class NoGuide(val id: String, val query: String, val expected: List<String>)
private data class View(val id: String, val query: String, val hide: Boolean, val rows: List<String>)
private data class Bound(val id: String, val query: String, val hide: Boolean, val cells: Int, val timelines: Int)
private data class Focus(
    val id: String, val from: Long, val to: Long, val channel: String,
    val index: Int, val title: String, val cellBound: Boolean,
)
private data class NavRight(
    val id: String, val from: Long, val to: Long, val channel: String,
    val start: Int, val right: Int, val back: Int,
)
private data class NavEdge(
    val id: String, val from: Long, val to: Long, val channel: String,
    val start: Int, val left: Int, val shiftDirection: Int,
)
private data class Parsed(
    var version: Int = -1,
    var windowFrom: Long = 0,
    var windowTo: Long = 0,
    val channels: List<Qa05Channel> = emptyList(),
    val programmes: List<Qa05Programme> = emptyList(),
    val expects: List<Expect> = emptyList(),
    val noGuides: List<NoGuide> = emptyList(),
    val views: List<View> = emptyList(),
    val bounds: List<Bound> = emptyList(),
    val focuses: List<Focus> = emptyList(),
    val navRights: List<NavRight> = emptyList(),
    val navEdges: List<NavEdge> = emptyList(),
)

/**
 * The same assertions as scripts/qa05/Qa05FixtureVerifier.java, written with no dependency on
 * Android or androidx.test. The instrumentation entry point calls [runAll] on the device; main()
 * lets the identical Kotlin assertions run on a JVM before a device is available.
 */
object Qa05GuideAssertions {
    private const val FIXTURE_BEGIN = "// QA05-FIXTURE-BEGIN"
    private const val FIXTURE_END = "// QA05-FIXTURE-END"

    private val EMBEDDED = """
